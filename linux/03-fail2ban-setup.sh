#!/usr/bin/env bash
# 03-fail2ban-setup.sh — brute-force protection via Fail2ban
# CIS Ubuntu 24.04 v1.0.0 — Section 5.2.x
# Usage: sudo ./03-fail2ban-setup.sh --dry-run | --apply

set -u
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

parse_mode "$@"
require_root

JAIL_LOCAL="/etc/fail2ban/jail.local"
BAN_TIME="${BAN_TIME:-1h}"
FIND_TIME="${FIND_TIME:-10m}"
MAX_RETRY="${MAX_RETRY:-5}"

log "Mode: ${MODE}"
log "Fail2ban jail target: $JAIL_LOCAL"

# ---------- Check installation ----------
if ! command -v fail2ban-client >/dev/null 2>&1; then
  warn "Fail2ban is not installed."
  do_or_dry apt-get update -qq
  do_or_dry apt-get install -y -qq fail2ban
fi

# ---------- Write jail.local ----------
# We write a minimal, safe jail.local that enables the default SSH jail
# and applies global policy. Using a dedicated local file keeps distro
# defaults in jail.conf untouched (best practice).
read -r -d '' JAIL_CONTENT <<EOF || true
# Generated by $SCRIPT_NAME at $(date -u +%FT%TZ)
# CIS Ubuntu 24.04 v1.0.0 — Section 5.2.x
[DEFAULT]
bantime  = $BAN_TIME
findtime = $FIND_TIME
maxretry = $MAX_RETRY
backend  = systemd

[sshd]
enabled = true
port    = ssh
logpath = %(sshd_log)s
EOF

if [[ "$MODE" == "apply" ]]; then
  printf '%s\n' "$JAIL_CONTENT" > "$JAIL_LOCAL"
  chmod 0644 "$JAIL_LOCAL"
  ok "Written: $JAIL_LOCAL"

  # Enable + (re)start
  systemctl enable fail2ban >>"$LOG_FILE" 2>&1 || warn "Failed to enable fail2ban"
  systemctl restart fail2ban >>"$LOG_FILE" 2>&1 || die "Failed to restart fail2ban"
  ok "fail2ban enabled and restarted"

  fail2ban-client status sshd | tee -a "$LOG_FILE" || warn "Could not query sshd jail status"
else
  log "[dry-run] Would write $JAIL_LOCAL:"
  printf '%s\n' "$JAIL_CONTENT" | sed 's/^/    /'
  log "[dry-run] Would enable + restart fail2ban."
fi
