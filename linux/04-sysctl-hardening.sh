#!/usr/bin/env bash
# 04-sysctl-hardening.sh — kernel network hardening
# CIS Ubuntu 24.04 v1.0.0 — Section 1.5
# Usage: sudo ./04-sysctl-hardening.sh --dry-run | --apply

set -u
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/lib/common.sh"

parse_mode "$@"
require_root
require_cmd sysctl

SYSCTL_CONF="/etc/sysctl.d/99-hardening.conf"

# ---------- Preflight ----------
log "Mode: ${MODE}"
log "Config target: ${SYSCTL_CONF}"

# ---------- CIS 1.5.x controls ----------
declare -A CTRL=(
  # 1.5.1 — disable IP forwarding (unless router)
  ["net.ipv4.ip_forward"]="0"
  # 1.5.2 — disable packet redirects
  ["net.ipv4.conf.all.send_redirects"]="0"
  ["net.ipv4.conf.default.send_redirects"]="0"
  # 1.5.3 — source routed packets
  ["net.ipv4.conf.all.accept_source_route"]="0"
  ["net.ipv4.conf.default.accept_source_route"]="0"
  ["net.ipv6.conf.all.accept_source_route"]="0"
  ["net.ipv6.conf.default.accept_source_route"]="0"
  # 1.5.4 — ICMP redirects
  ["net.ipv4.conf.all.accept_redirects"]="0"
  ["net.ipv4.conf.default.accept_redirects"]="0"
  ["net.ipv4.conf.all.secure_redirects"]="0"
  ["net.ipv4.conf.default.secure_redirects"]="0"
  ["net.ipv6.conf.all.accept_redirects"]="0"
  # 1.5.5 — log martians
  ["net.ipv4.conf.all.log_martians"]="1"
  ["net.ipv4.conf.default.log_martians"]="1"
  # 1.5.6 — ignore broadcast pings
  ["net.ipv4.icmp_echo_ignore_broadcasts"]="1"
  # 1.5.7 — ignore bogus ICMP
  ["net.ipv4.icmp_ignore_bogus_error_responses"]="1"
  # 1.5.8 — reverse path filtering
  ["net.ipv4.conf.all.rp_filter"]="1"
  ["net.ipv4.conf.default.rp_filter"]="1"
  # 1.5.9 — SYN cookies
  ["net.ipv4.tcp_syncookies"]="1"
  # 1.5.10 — disable IPv6 router advertisements
  ["net.ipv6.conf.all.accept_ra"]="0"
  ["net.ipv6.conf.default.accept_ra"]="0"
)

# ---------- Compose file ----------
new_content="# Generated by $SCRIPT_NAME at $(date -u +%FT%TZ)\n"
new_content+="# CIS Ubuntu 24.04 v1.0.0 — Section 1.5\n"
for k in "${!CTRL[@]}"; do
  new_content+="${k} = ${CTRL[$k]}\n"
done

if [[ "$MODE" == "apply" ]]; then
  printf '%b' "$new_content" > "$SYSCTL_CONF"
  ok "Written: $SYSCTL_CONF"
  sysctl --system >>"$LOG_FILE" 2>&1 || die "sysctl --system failed"
  ok "sysctl reloaded"
else
  log "[dry-run] Would write $SYSCTL_CONF with ${#CTRL[@]} controls:"
  printf '%b' "$new_content" | sed 's/^/    /'
fi
